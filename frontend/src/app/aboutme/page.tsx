function NeofetchRow({ label, value }: { label: string; value: string }) {
  return (
    <div className={styles.neofetchRow}>
      <span className={styles.neofetchLabel}>{label}</span>
      <span className={styles.neofetchSep}>:</span>
      <span className={styles.neofetchValue}>{value}</span>
    </div>
  );
}

function SkillGroup({ title, skills }: { title: string; skills: Skill[] }) {
  const nameWidth = Math.max(...skills.map((s) => s.name.length), 12) + 2;
  return (
    <div className={styles.skillGroup}>
      <div className={styles.skillGroupTitle}># {title}</div>
      <pre>
        {skills.map((s) => {
          const score = LEVEL_SCORE[s.level] ?? 0;
          const levelCls = LEVEL_CLASS[s.level] ?? "";
          return (
            <span key={s.name}>
              <span className={styles.skillName}>{s.name.padEnd(nameWidth)}</span>
              <span className={levelCls}>{"█".repeat(score)}</span>
              <span className={styles.barEmpty}>
                {"░".repeat(BAR_WIDTH - score)}
              </span>
              <span className={levelCls}>{`  ${LEVEL_LABEL[s.level] ?? ""}`}</span>
              {"\n"}
            </span>
          );
        })}
      </pre>
    </div>
  );
}

function LegendChip({ cls, label }: { cls: string; label: string }) {
  return (
    <span className={styles.legendChip}>
      <span className={cls}>██</span> {label}
    </span>
  );
}
