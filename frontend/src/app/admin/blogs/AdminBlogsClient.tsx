"use client";

import { useInfiniteQuery } from "@tanstack/react-query";
import { create } from "@bufbuild/protobuf";
import { ConnectError } from "@connectrpc/connect";
import {
  ListBlogsRequestSchema,
  type Blog,
} from "@amirsalarsafaei/autogenerated/blogs/blogs_pb";
import { useSearchParams } from "next/navigation";
import BlogsList from "@/components/BlogsList/BlogsList";
import { withAuth } from "@/clients/grpc";
import { useGrpc } from "@/providers/GrpcProvider";
import { useAuth } from "@/hooks/useAuth";
import { Button } from "@/components/Button/Button";
import styles from "./page.module.scss";

export default function AdminBlogsClient() {
  const searchParams = useSearchParams();
  const { blogs_client } = useGrpc();
  const { token } = useAuth();

  const getBlogs = async ({ pageParam = "" }) => {
    const req = create(ListBlogsRequestSchema, {
      pageSize: Number(searchParams.get("page-size")) || 10,
      pageToken: pageParam,
    });

    try {
      return await blogs_client.listBlogs(req, withAuth(token));
    } catch (error) {
      if (error instanceof ConnectError) {
        console.error("gRPC Error: ", error.message, error.code);
      }
      throw error;
    }
  };

  const {
    isFetching,
    data,
    isLoadingError,
    fetchNextPage,
    hasNextPage,
    isFetchingNextPage,
    refetch,
  } = useInfiniteQuery({
    queryKey: ["blogs", searchParams.get("page-size")],
    queryFn: getBlogs,
    getNextPageParam: (lastPage) =>
      lastPage.nextPageToken.length === 0 ? undefined : lastPage.nextPageToken,
    initialPageParam: "",
    // Coming back from the editor should always show the current blog set.
    refetchOnMount: "always",
    refetchOnWindowFocus: true,
  });

  return (
    <>
      <div className={styles.toolbar}>
        <h1 className={styles.title}>blogs</h1>
        <Button variant="primary" size="sm" href="/admin/blogs/new">
          + new post
        </Button>
      </div>
      <BlogsList
        blogs={
          data?.pages?.reduce(
            (collected, page) => [...collected, ...page.blogs],
            [] as Blog[],
          ) ?? []
        }
        isLoadingError={isLoadingError}
        isFetching={isFetching}
        isFetchingNextPage={isFetchingNextPage}
        hasNextPage={!!hasNextPage}
        onLoadMore={() => {
          void fetchNextPage();
        }}
        onRetry={() => {
          void refetch();
        }}
        isAdmin
      />
    </>
  );
}
