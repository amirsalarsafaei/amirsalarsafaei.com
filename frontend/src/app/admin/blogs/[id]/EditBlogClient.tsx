"use client";
import { useState, useEffect } from "react";
import { useGrpc } from "@/providers/GrpcProvider";
import BlogEditor, { SubmitBlogProps } from "../components/BlogEditor";
import { useAuth } from "@/hooks/useAuth";
import { create } from "@bufbuild/protobuf";
import {
  UpdateBlogRequestSchema,
  GetBlogRequestSchema,
  PublishBlogRequestSchema,
  SetBlogTagsRequestSchema,
  type Blog,
} from "@amirsalarsafaei/autogenerated/blogs/blogs_pb";
import { withAuth } from "@/clients/grpc";
import { useQueryClient } from "@tanstack/react-query";
import { revalidateBlog } from "@/utils/revalidate";
import styles from "./page.module.scss";

export default function EditBlogClient({ id }: { id: string }) {
  const params = { id };
  const { blogs_client, tags_client } = useGrpc();
  const { token } = useAuth();
  const queryClient = useQueryClient();
  const [blog, setBlog] = useState<Blog | null>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [isPublishing, setIsPublishing] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [isFetching, setIsFetching] = useState(true);

  useEffect(() => {
    const fetchBlog = async () => {
      try {
        const blog = await getBlog(params.id);
        if (blog) {
          setBlog(blog);
        } else {
          setError("Blog not found");
        }
      } catch (err) {
        setError("Failed to load blog");
        console.error(err);
      } finally {
        setIsFetching(false);
      }
    };

    fetchBlog();
  }, [params.id]);

  const getBlog = async (id: string): Promise<Blog | null> => {
    try {
      const req = create(GetBlogRequestSchema, { id });
      const resp = await blogs_client.getBlog(req, withAuth(token));
      return resp.blog || null;
    } catch (err) {
      console.error("Failed to fetch blog:", err);
      throw err;
    }
  };

  const updateBlog = async (submitBlog: SubmitBlogProps) => {
    if (isLoading) {
      return;
    }
    setIsLoading(true);
    const req = create(UpdateBlogRequestSchema, {
      id: params.id,
      title: submitBlog.title,
      content: submitBlog.content,
      imageUrl: submitBlog.imageUrl,
    });
    const metadata = withAuth(token);
    try {
      await blogs_client.updateBlog(req, metadata);
      try {
        await tags_client.setBlogTags(
          create(SetBlogTagsRequestSchema, {
            blogId: params.id,
            tagNames: submitBlog.tags,
          }),
          metadata,
        );
      } catch (err) {
        console.error("could not set blog tags:", err);
      }

      await revalidateBlog(token, params.id);
      void queryClient.invalidateQueries({ queryKey: ["blogs"] });
      void queryClient.invalidateQueries({ queryKey: ["published-blogs"] });

      setIsLoading(false);
    } catch (err) {
      console.error("Failed to update blog:", err);
      setIsLoading(false);
      throw err;
    }
  };

  const publishBlog = async (id: string) => {
    const req = create(PublishBlogRequestSchema, {
      id,
    });

    try {
      await blogs_client.publishBlog(req, withAuth(token));
    } catch (err) {
      console.error("Failed to publish blog:", err);
      throw err;
    }
  };
  const handlePublish = async () => {
    if (isPublishing) {
      return;
    }
    setIsPublishing(true);
    try {
      await publishBlog(params.id);
      await revalidateBlog(token, params.id);
      void queryClient.invalidateQueries({ queryKey: ["blogs"] });
      void queryClient.invalidateQueries({ queryKey: ["published-blogs"] });
    } catch (err) {
      setError("Failed to publish blog");
    } finally {
      setIsPublishing(false);
    }
  };

  if (isFetching) {
    return <div className={styles.loading}>Loading...</div>;
  }

  if (error) {
    return <div className={styles.error}>{error}</div>;
  }

  return (
    <BlogEditor
      onSubmit={updateBlog}
      buttonLabel="Update Blog"
      initialImageUrl={blog?.imageUrl}
      initialTitle={blog?.title ?? ""}
      initialContent={blog?.content ?? ""}
      isSubmiting={isLoading}
      initialTags={blog?.tags ?? []}
      headerButtons={[
        { label: "Publish", disabled: isPublishing, onClick: handlePublish },
      ]}
    />
  );
}
