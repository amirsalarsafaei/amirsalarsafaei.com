"use client";
import { useState } from "react";
import { useGrpc } from "@/providers/GrpcProvider";
import BlogEditor, { SubmitBlogProps } from "../components/BlogEditor";
import { useAuth } from "@/hooks/useAuth";
import { create } from "@bufbuild/protobuf";
import {
  CreateBlogRequestSchema,
  SetBlogTagsRequestSchema,
} from "@amirsalarsafaei/autogenerated/blogs/blogs_pb";
import { withAuth } from "@/clients/grpc";
import { useRouter } from "next/navigation";
import { useQueryClient } from "@tanstack/react-query";
import { revalidateBlog } from "@/utils/revalidate";
import "./page.scss";

export default function NewBlog() {
  const { blogs_client, tags_client } = useGrpc();
  const { token } = useAuth();
  const router = useRouter();
  const queryClient = useQueryClient();
  const [isLoading, setIsLoading] = useState(false);

  const handleCreate = async (submitBlog: SubmitBlogProps) => {
    if (!submitBlog.title.trim()) {
      alert("Please enter a title");
      return;
    }
    setIsLoading(true);

    const req = create(CreateBlogRequestSchema, {
      title: submitBlog.title,
      content: submitBlog.content,
      imageUrl: submitBlog.imageUrl,
    });
    try {
      const metadata = withAuth(token);
      const resp = await blogs_client.createBlog(req, metadata);
      try {
        await tags_client.setBlogTags(
          create(SetBlogTagsRequestSchema, {
            blogId: resp.blog?.id,
            tagNames: submitBlog.tags,
          }),
          metadata,
        );
      } catch (err) {
        console.error("could not set blog tags:", err);
      }

      await revalidateBlog(token, resp.blog?.id);
      void queryClient.invalidateQueries({ queryKey: ["blogs"] });
      void queryClient.invalidateQueries({ queryKey: ["published-blogs"] });

      router.push(`/admin/blogs/${resp.blog?.id}`);
      setIsLoading(false);
    } catch (err) {
      console.error("Failed to create blog:", err);
      setIsLoading(false);
      throw err;
    }
  };

  return (
    <BlogEditor
      onSubmit={handleCreate}
      isSubmiting={isLoading}
      initialImageUrl={undefined}
      initialTags={[]}
      initialTitle=""
      initialContent=""
      buttonLabel="Create New Blog"
    />
  );
}
