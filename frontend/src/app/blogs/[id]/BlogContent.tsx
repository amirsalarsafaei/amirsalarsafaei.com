"use client";

import { Suspense } from "react";
import Link from "next/link";
import Image from "next/image";
import { type GetBlogResponse } from "@amirsalarsafaei/autogenerated/blogs/blogs_pb";
import { timestampToDate } from "@/utils/protobuf";
import Loading from "@/components/Loading/Loading";
import { Chip } from "@/components/Chip/Chip";
import Markdown from "../../../components/Markdown/Markdown";
import styles from "./BlogContent.module.scss";

const dateFormatter = new Intl.DateTimeFormat("en-US", {
  year: "numeric",
  month: "long",
  day: "numeric",
});

export default function BlogContent({
  initialData,
}: {
  initialData: GetBlogResponse;
}) {
  if (!initialData || !initialData.blog) {
    return (
      <div className={styles.messageContainer}>
        <div className={styles.prompt}>$ cat ./blog.md</div>
        <div className={styles.message}>Blog not found</div>
        <p className={styles.subMessage}>
          The post you're looking for doesn't exist or has been removed.
        </p>
        <Link href="/blogs" className={styles.backLink}>
          ← cd ../blogs
        </Link>
      </div>
    );
  }

  const blog = initialData.blog;
  const publishedAt = timestampToDate(blog.publishedAt);
  const content = blog.content ?? "";
  const wordCount = content.trim().split(/\s+/).filter(Boolean).length;
  const readingTime = Math.max(1, Math.round(wordCount / 220));

  return (
    <Suspense fallback={<Loading message={`${blog.title} is loading`} />}>
      <article className={styles.blogContainer}>
        <Link href="/blogs" className={styles.backLink}>
          ← cd ../blogs
        </Link>

        <header className={styles.blogHeader}>
          <h1 className={styles.blogTitle}>{blog.title}</h1>

          <div className={styles.blogMeta}>
            {publishedAt && (
              <time dateTime={publishedAt.toISOString()}>
                {dateFormatter.format(publishedAt)}
              </time>
            )}
            <span className={styles.metaDivider} aria-hidden>
              ·
            </span>
            <span>{readingTime} min read</span>
          </div>

          {blog.tags && blog.tags.length > 0 && (
            <div className={styles.tagContainer}>
              {blog.tags.map((tag) => (
                <Chip key={tag.id} label={tag.name} />
              ))}
            </div>
          )}

          {blog.imageUrl && (
            <div className={styles.blogImage}>
              <Image
                src={blog.imageUrl}
                alt={blog.title}
                width={800}
                height={400}
                priority
                className={styles.image}
                quality={80}
                sizes="(max-width: 768px) 100vw, 900px"
                // Covers are served by the upload host; skip the server-side
                // optimizer so the browser can load them directly.
                unoptimized
              />
            </div>
          )}
        </header>

        <Markdown content={content} />

        <footer className={styles.blogFooter}>
          <Link href="/blogs" className={styles.backLink}>
            ← all posts
          </Link>
        </footer>
      </article>
    </Suspense>
  );
}
