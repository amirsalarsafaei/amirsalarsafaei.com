import {
  Blog_State,
  type Blog,
} from "@amirsalarsafaei/autogenerated/blogs/blogs_pb";
import { timestampToDate } from "@/utils/protobuf";
import { absoluteUrl, blogDescription, getSiteUrl } from "@/utils/seo";

/**
 * schema.org BlogPosting + BreadcrumbList for a single post. Rendered on the
 * server so crawlers see it in the initial HTML (use the Rich Results Test to
 * validate). Drafts are never exposed to crawlers.
 */
export default function BlogJsonLd({ blog }: { blog: Blog }) {
  if (blog.state !== Blog_State.PUBLISHED) {
    return null;
  }

  const siteUrl = getSiteUrl();
  const url = `${siteUrl}/blogs/${blog.id}`;
  const image = absoluteUrl(blog.imageUrl, siteUrl);
  const datePublished = timestampToDate(
    blog.publishedAt ?? blog.createdAt,
  )?.toISOString();
  const tags = blog.tags.map((tag) => tag.name);

  const graph = {
    "@context": "https://schema.org",
    "@graph": [
      {
        "@type": "BlogPosting",
        "@id": `${url}#article`,
        mainEntityOfPage: { "@type": "WebPage", "@id": url },
        headline: blog.title,
        description: blogDescription(blog.title, blog.content),
        image: image ? [image] : undefined,
        datePublished,
        dateModified: datePublished,
        inLanguage: "en",
        url,
        keywords: tags.length > 0 ? tags.join(", ") : undefined,
        articleSection: tags[0],
        author: {
          "@type": "Person",
          name: "Amirsalar Safaei",
          url: siteUrl,
        },
        publisher: {
          "@type": "Organization",
          name: "Amirsalar Safaei",
          url: siteUrl,
          logo: {
            "@type": "ImageObject",
            url: `${siteUrl}/icon.png`,
          },
        },
      },
      {
        "@type": "BreadcrumbList",
        "@id": `${url}#breadcrumb`,
        itemListElement: [
          {
            "@type": "ListItem",
            position: 1,
            name: "Home",
            item: siteUrl,
          },
          {
            "@type": "ListItem",
            position: 2,
            name: "Blogs",
            item: `${siteUrl}/blogs`,
          },
          {
            "@type": "ListItem",
            position: 3,
            name: blog.title,
            item: url,
          },
        ],
      },
    ],
  };

  return (
    <script
      type="application/ld+json"
      // Escape "<" so post text can never close the script element early.
      dangerouslySetInnerHTML={{
        __html: JSON.stringify(graph).replace(/</g, "\\u003c"),
      }}
    />
  );
}
