import { Metadata } from "next";
import { create } from "@bufbuild/protobuf";
import {
  Blog_State,
  GetBlogRequestSchema,
} from "@amirsalarsafaei/autogenerated/blogs/blogs_pb";
import { createGrpcClients } from "@/clients/grpc";
import { timestampToDate } from "@/utils/protobuf";
import { absoluteUrl, blogDescription, getSiteUrl } from "@/utils/seo";

const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export async function generateMetadata({
  params,
}: {
  params: Promise<{ id: string }>;
}): Promise<Metadata> {
  if (process.env.NEXT_BUILD_SKIP_BACKEND === "1") {
    return { title: "Blog", description: "Blog post" };
  }

  const { id } = await params;

  // Invalid ids can never resolve to a post; keep them out of the index
  // instead of emitting a canonical URL for a page that renders "not found".
  if (!UUID_RE.test(id)) {
    return {
      title: "Blog Not Found",
      description: "The requested blog post could not be found.",
      robots: { index: false, follow: false },
    };
  }

  const { blogs_client } = createGrpcClients();

  try {
    const req = create(GetBlogRequestSchema, { id });
    const data = await blogs_client.getBlog(req);

    if (!data?.blog) {
      return {
        title: "Blog Not Found",
        description: "The requested blog post could not be found.",
        robots: { index: false, follow: false },
      };
    }

    const blog = data.blog;
    const siteUrl = getSiteUrl();
    const canonicalUrl = `${siteUrl}/blogs/${id}`;
    const description = blogDescription(blog.title, blog.content);
    const tags = blog.tags.map((tag) => tag.name);
    const coverImage = absoluteUrl(blog.imageUrl, siteUrl);
    // icon.png is 180×180; blog-1.png is the real 1024×576 social fallback.
    const imageUrl = coverImage ?? `${siteUrl}/blog-1.png`;
    const publishedTime = timestampToDate(
      blog.publishedAt ?? blog.createdAt,
    )?.toISOString();
    // The API has no updated_at; publishedAt is the best available signal and
    // keeps Google from treating the post as constantly modified.
    const modifiedTime = publishedTime;
    const isPublished = blog.state === Blog_State.PUBLISHED;

    return {
      metadataBase: new URL(siteUrl),
      title: blog.title,
      description,
      keywords: tags,
      authors: [{ name: "Amirsalar Safaei", url: siteUrl }],
      creator: "Amirsalar Safaei",
      publisher: "Amirsalar Safaei",
      robots: isPublished
        ? {
            index: true,
            follow: true,
            googleBot: {
              index: true,
              follow: true,
              "max-video-preview": -1,
              "max-image-preview": "large",
              "max-snippet": -1,
            },
          }
        : { index: false, follow: false },
      alternates: {
        canonical: canonicalUrl,
      },
      openGraph: {
        type: "article",
        title: blog.title,
        description,
        url: canonicalUrl,
        siteName: "Amirsalar Safaei",
        locale: "en_US",
        publishedTime,
        modifiedTime,
        authors: ["Amirsalar Safaei"],
        tags,
        section: tags[0],
        images: [
          coverImage
            ? // Upload dimensions are unknown; let the consumer scale it.
              { url: coverImage, alt: blog.title }
            : { url: imageUrl, width: 1024, height: 576, alt: blog.title },
        ],
      },
      other: {
        "telegram-channel": "@amirsalarsafaei",
        "telegram:card": "summary_large_image",
        "telegram:image": imageUrl,
        "telegram:title": blog.title,
        "telegram:description": description,
        "telegram:site": "@amirsalarsafaei",
      },
      twitter: {
        card: "summary_large_image",
        title: blog.title,
        description,
        images: [imageUrl],
        creator: "@amirsalarsafaei",
        site: "@amirsalarsafaei",
      },
    };
  } catch (error) {
    // Do not emit noindex on a transient backend failure — that could deindex a
    // real post. The page itself will surface an error for this same request.
    console.error("Error generating metadata:", error);
    return {
      title: "Blog",
      description: "Read AmirSalar Safaei's latest blog posts",
    };
  }
}
