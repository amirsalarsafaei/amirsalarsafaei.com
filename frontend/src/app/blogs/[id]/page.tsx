import { notFound } from "next/navigation";
import BlogContent from "./BlogContent";
import BlogJsonLd from "./BlogJsonLd";
import { create } from "@bufbuild/protobuf";
import {
  GetBlogRequestSchema,
  ListPublishedBlogsRequestSchema,
  type GetBlogResponse,
} from "@amirsalarsafaei/autogenerated/blogs/blogs_pb";
import { createGrpcClients } from "@/clients/grpc";

// Pre-render every published blog at build time against the live backend and
// refresh in the background (ISR). dynamicParams=true lets blogs published
// after the build still render on first request instead of 404ing.
export const revalidate = 300;
export const dynamicParams = true;

export { generateMetadata } from "./page.metadata";

const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export async function generateStaticParams(): Promise<{ id: string }[]> {
  // No backend during pure/offline Nix builds: pre-render nothing and let every
  // blog be generated on demand (dynamicParams=true). The on-server build runs
  // against the live backend and pre-renders the real set.
  if (process.env.NEXT_BUILD_SKIP_BACKEND === "1") {
    return [];
  }

  const { blogs_client } = createGrpcClients();

  const params: { id: string }[] = [];
  let pageToken = "";

  try {
    do {
      const res = await blogs_client.listPublishedBlogs(
        create(ListPublishedBlogsRequestSchema, { pageSize: 100, pageToken }),
      );
      params.push(...res.blogs.map((blog) => ({ id: blog.id })));
      pageToken = res.nextPageToken;
    } while (pageToken);
  } catch (error) {
    // Docker/CI builds often have no backend available. Return no params and
    // let `dynamicParams` + ISR render each post on first request instead of
    // failing the whole image build.
    console.warn(
      "Could not pre-render blog posts (backend unavailable); falling back to on-demand rendering:",
      error,
    );
    return [];
  }

  return params;
}

export default async function BlogPage({
  params,
}: {
  params: Promise<{ id: string }>;
}) {
  const { id } = await params;

  // Unknown ids can never resolve to a post; respond 404 instead of a 200
  // "not found" page so search engines do not index soft 404s.
  if (!UUID_RE.test(id)) {
    notFound();
  }

  const { blogs_client } = createGrpcClients();
  const req = create(GetBlogRequestSchema, { id });

  let data: GetBlogResponse;
  try {
    data = await blogs_client.getBlog(req);
  } catch (error) {
    // Surface real backend failures (error boundary / 5xx) rather than serving
    // a cached soft 404 that could deindex an existing post.
    console.error("Failed to fetch blog:", error);
    throw error;
  }

  if (!data.blog) {
    notFound();
  }

  return (
    <>
      <BlogJsonLd blog={data.blog} />
      <BlogContent initialData={data} />
    </>
  );
}
