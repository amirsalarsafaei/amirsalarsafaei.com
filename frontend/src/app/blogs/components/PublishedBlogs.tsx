"use client";

import { useInfiniteQuery } from "@tanstack/react-query";
import { create } from "@bufbuild/protobuf";
import { ConnectError } from "@connectrpc/connect";
import {
  ListPublishedBlogsRequestSchema,
  type Blog,
  type ListPublishedBlogsResponse,
} from "@amirsalarsafaei/autogenerated/blogs/blogs_pb";
import { useSearchParams } from "next/navigation";
import BlogsList from "@/components/BlogsList/BlogsList";
import { useGrpc } from "@/providers/GrpcProvider";

export default function BlogsListClient({
  initialData,
  initialDataUpdatedAt,
}: {
  initialData: Awaited<ListPublishedBlogsResponse>;
  initialDataUpdatedAt: number;
}) {
  const searchParams = useSearchParams();
  const { blogs_client } = useGrpc();

  const getPublishedBlogs = async ({ pageParam = "" }) => {
    const req = create(ListPublishedBlogsRequestSchema, {
      pageSize: Number(searchParams.get("page-size")) || 10,
      pageToken: pageParam,
    });

    try {
      return await blogs_client.listPublishedBlogs(req);
    } catch (error) {
      console.log(error);
      if (error instanceof ConnectError) {
        console.error("gRPC Error: ", error.message, error.code);
        throw error;
      }
      throw error;
    }
  };

  const {
    isFetching,
    data,
    isLoadingError,
    fetchNextPage,
    hasNextPage,
    isFetchingNextPage,
    refetch,
  } = useInfiniteQuery({
    queryKey: ["published-blogs", searchParams.get("page-size")],
    queryFn: getPublishedBlogs,
    getNextPageParam: (lastPage) => {
      if (lastPage.nextPageToken.length == 0) {
        return undefined;
      }
      return lastPage.nextPageToken;
    },
    initialDataUpdatedAt: initialDataUpdatedAt,
    initialPageParam: "",
    initialData: {
      pages: [initialData],
      pageParams: [""],
    },
    // The static shell is built without a backend, so its initial list can be
    // empty and its timestamp fresh. Always reconcile with the API on mount.
    refetchOnMount: "always",
    refetchOnWindowFocus: true,
  });

  return (
    <BlogsList
      blogs={
        data?.pages?.reduce(
          (collected, page) => [...collected, ...page.blogs],
          [] as Blog[],
        ) ?? []
      }
      isLoadingError={isLoadingError}
      isFetching={isFetching}
      isFetchingNextPage={isFetchingNextPage}
      hasNextPage={!!hasNextPage}
      onLoadMore={() => {
        void fetchNextPage();
      }}
      onRetry={() => {
        void refetch();
      }}
      isAdmin={false}
    />
  );
}
