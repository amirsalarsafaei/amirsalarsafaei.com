async function getInitialBlogs() {
  // Pure/offline Nix builds (NEXT_BUILD_SKIP_BACKEND=1) have no backend to talk
  // to; return an empty page so `next build` still succeeds. The real content
  // is fetched during the on-server build that runs against the live backend.
  if (process.env.NEXT_BUILD_SKIP_BACKEND === "1") {
    return create(ListPublishedBlogsResponseSchema, {
      blogs: [],
      nextPageToken: "",
    });
  }

  const { blogs_client } = createGrpcClients();

  const req = create(ListPublishedBlogsRequestSchema, {
    pageSize: 10,
    pageToken: "",
  });

  try {
    return await blogs_client.listPublishedBlogs(req);
  } catch (error) {
    // Degrade to the empty state instead of taking the whole page down; ISR
    // will retry against the backend on the next revalidation window.
    console.error("Failed to fetch initial blogs:", error);
    return create(ListPublishedBlogsResponseSchema, {
      blogs: [],
      nextPageToken: "",
    });
  }
}

export default async function PublishedBlogs() {
  const initialData = await getInitialBlogs();

  return (
    // `PublishedBlogs` reads search params on the client; the Suspense
    // boundary lets the layout/nav still server-render instead of bailing the
    // whole route out to client-only rendering.
    <Suspense fallback={<Loading message="blogs" />}>
      <BlogsListClient
        initialData={initialData}
        initialDataUpdatedAt={Date.now()}
      />
    </Suspense>
  );
}
