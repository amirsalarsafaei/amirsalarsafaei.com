function makeGrilleTexture() {
  const size = 256;
  const canvas = document.createElement("canvas");
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext("2d");
  if (!ctx) return new THREE.CanvasTexture(canvas);

  ctx.fillStyle = "#ffffff";
  ctx.fillRect(0, 0, size, size);

  ctx.globalCompositeOperation = "destination-out";
  const centre = size / 2;
  for (let ring = 0; ring < 8; ring += 1) {
    const radius = 20 + ring * 15;
    const count = Math.max(6, Math.round((Math.PI * 2 * radius) / 15));
    for (let i = 0; i < count; i += 1) {
      const angle = (i / count) * Math.PI * 2 + ring * 0.24;
      ctx.beginPath();
      ctx.arc(
        centre + Math.cos(angle) * radius,
        centre + Math.sin(angle) * radius,
        3.4,
        0,
        Math.PI * 2,
      );
      ctx.fill();
    }
  }

  const texture = new THREE.CanvasTexture(canvas);
  texture.anisotropy = 4;
  return texture;
}

function makeWoodTexture() {
  const size = 256;
  const canvas = document.createElement("canvas");
  canvas.width = size;
  canvas.height = size;
  const ctx = canvas.getContext("2d");
  if (!ctx) return new THREE.CanvasTexture(canvas);

  ctx.fillStyle = WOOD;
  ctx.fillRect(0, 0, size, size);

  for (let i = 0; i < 170; i += 1) {
    const y = Math.random() * size;
    const x = Math.random() * size - 40;
    const length = 60 + Math.random() * 220;
    const light = Math.random() > 0.5;
    ctx.strokeStyle = light
      ? `rgba(255, 226, 190, ${0.02 + Math.random() * 0.05})`
      : `rgba(43, 27, 17, ${0.02 + Math.random() * 0.06})`;
    ctx.lineWidth = 0.5 + Math.random() * 1.8;
    ctx.beginPath();
    ctx.moveTo(x, y);
    ctx.bezierCurveTo(
      x + length * 0.33,
      y + (Math.random() - 0.5) * 6,
      x + length * 0.66,
      y + (Math.random() - 0.5) * 8,
      x + length,
      y + (Math.random() - 0.5) * 4,
    );
    ctx.stroke();
  }

  const texture = new THREE.CanvasTexture(canvas);
  texture.wrapS = THREE.RepeatWrapping;
  texture.wrapT = THREE.RepeatWrapping;
  texture.repeat.set(2, 1);
  texture.colorSpace = THREE.SRGBColorSpace;
  texture.anisotropy = 4;
  return texture;
}

function makeSheenTexture() {
  const width = 128;
  const height = 64;
  const canvas = document.createElement("canvas");
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext("2d");
  if (!ctx) return new THREE.CanvasTexture(canvas);

  const gradient = ctx.createLinearGradient(0, 0, width, height);
  gradient.addColorStop(0, "rgba(255, 255, 255, 0.14)");
  gradient.addColorStop(0.35, "rgba(255, 255, 255, 0.03)");
  gradient.addColorStop(0.55, "rgba(255, 255, 255, 0)");
  gradient.addColorStop(1, "rgba(255, 255, 255, 0.05)");
  ctx.fillStyle = gradient;
  ctx.fillRect(0, 0, width, height);

  const texture = new THREE.CanvasTexture(canvas);
  texture.colorSpace = THREE.SRGBColorSpace;
  return texture;
}

