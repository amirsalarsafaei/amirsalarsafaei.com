// ── Main Component ──────────────────────────────────────────────────────────

export default function MusicPlayer() {
  const { spotify_client } = useGrpc();

  const [data, setData] = useState<GetRecentlyPlayedSongResponse | undefined>();
  const [status, setStatus] = useState<"pending" | "error" | "success" | "demo">("pending");
  const [isPlaying, setIsPlaying] = useState(false);

  useEffect(() => {
    let active = true;
    let subscription: { unsubscribe: () => void } | undefined;
    let retry: ReturnType<typeof setTimeout> | undefined;
    let fallback: ReturnType<typeof setTimeout> | undefined;
    let receivedSpotifyData = false;

    const showDevelopmentFallback = () => {
      if (!active || !IS_DEVELOPMENT || receivedSpotifyData) return;
      setData(DEV_FALLBACK_TRACK);
      setIsPlaying(true);
      setStatus("demo");
    };

    const subscribe = () => {
      if (!active) return;
      const request = GetRecentlyPlayedSongRequest.create();
      subscription = spotify_client.StreamRecentlyPlayedSong(request).subscribe({
        next: (song: GetRecentlyPlayedSongResponse) => {
          receivedSpotifyData = true;
          if (fallback) clearTimeout(fallback);
          setData(song);
          setIsPlaying(!!song.playing);
          setStatus("success");
        },
        error: (err: unknown) => {
          console.error("Spotify stream error:", err);
          if (!active) return;
          if (IS_DEVELOPMENT && !receivedSpotifyData) {
            setData(DEV_FALLBACK_TRACK);
            setIsPlaying(true);
            setStatus("demo");
          } else if (!receivedSpotifyData) {
            setStatus("error");
          }
          retry = setTimeout(subscribe, RESUBSCRIBE_DELAY);
        },
        complete: () => {
          if (active) retry = setTimeout(subscribe, RESUBSCRIBE_DELAY);
        },
      });
    };

    subscribe();
    if (IS_DEVELOPMENT) {
      fallback = setTimeout(showDevelopmentFallback, DEV_FALLBACK_DELAY);
    }

    return () => {
      active = false;
      subscription?.unsubscribe();
      if (retry) clearTimeout(retry);
      if (fallback) clearTimeout(fallback);
    };
  }, [spotify_client]);

  const isPending = status === "pending";
  const isLoadingError = status === "error";
  const isSuccess = status === "success";
  const isDemo = status === "demo";
  const hasTrack = isSuccess || isDemo;
  const durationMs = readMs(data?.durationMs);

  const progressStateRef = useRef<ProgressState>({
    baseMs: 0,
    startedAt: 0,
    durationMs: 0,
    playing: false,
  });

  useEffect(() => {
    progressStateRef.current = {
      baseMs: readMs(data?.progressMs),
      startedAt: Date.now(),
      durationMs,
      playing: isPlaying,
    };
  }, [data?.progressMs, isPlaying, durationMs]);

  const effectivePlaying = isPlaying || !!data?.playing;

  return (
    <group
      rotation={[0, -Math.PI / 7, 0]}
      position={PLAYER_POSITION}
      scale={PLAYER_SCALE}
    >
      <group rotation={[-0.05, 0, 0]}>
        <pointLight position={[1.6, 1.6, 1.0]} color={TERM_CYAN} intensity={0.2} distance={4} />

        <Desk />
        <CRTMonitor />
        <CRTGlow playing={effectivePlaying} />
        <Scanlines />

        <Suspense fallback={null}>
          {isPending || isLoadingError ? (
            <Text
              color={isPending ? TERM_GREEN : TERM_AMBER}
              font={FONT_BOLD}
              fontSize={0.16}
              position={[0, 0.4, SCREEN_CONTENT_Z]}
              maxWidth={3.0}
              textAlign="center"
              anchorX="center"
              anchorY="middle"
            >
              {isPending ? "$ connecting to spotify..." : "$ ERR: spotify unavailable"}
            </Text>
          ) : (
            <>
              {hasTrack && data?.albumArtUrl ? (
                <AlbumArt albumUrl={data.albumArtUrl} />
              ) : (
                <AlbumArtFallback />
              )}

              <ConnectionBadge demo={isDemo} />
              <Oscilloscope playing={effectivePlaying} />

              <TrackReadout
                track={hasTrack && data ? data.track : ""}
                artist={hasTrack && data ? data.artist : ""}
                playing={effectivePlaying}
              />

              <CLIProgressBar stateRef={progressStateRef} playing={effectivePlaying} />

              <TransportKeys
                playing={effectivePlaying}
                onPlay={() => setIsPlaying(true)}
                onPause={() => setIsPlaying(false)}
              />
            </>
          )}
        </Suspense>

      </group>
    </group>
  );
}
