// ── Transport keys ─────────────────────────────────────────────────────────

function TransportKey({
  position,
  width,
  height,
  color,
  icon,
  iconKind,
  label,
  active = false,
  energyRef,
  onClick,
}: {
  position: [number, number, number];
  width: number;
  height: number;
  color: string;
  icon: string;
  iconKind: IconKind;
  label: string;
  active?: boolean;
  energyRef: RefObject<number>;
  onClick: () => void;
}) {
  const [hovered, setHovered] = useState(false);
  const [pressed, setPressed] = useState(false);
  const keyRef = useRef<THREE.Group>(null);
  const materialRef = useRef<THREE.MeshStandardMaterial>(null);

  useFrame((_, delta) => {
    if (keyRef.current) {
      const target = pressed ? 0.046 : 0.085;
      keyRef.current.position.z = THREE.MathUtils.damp(
        keyRef.current.position.z,
        target,
        18,
        delta,
      );
    }
    if (materialRef.current) {
      const target = active
        ? 0.22 + energyRef.current * 0.16
        : hovered
          ? 0.06
          : 0;
      materialRef.current.emissiveIntensity = THREE.MathUtils.damp(
        materialRef.current.emissiveIntensity,
        target,
        10,
        delta,
      );
    }
  });

  return (
    <group position={position}>
      <group ref={keyRef} position={[0, 0, 0.085]}>
        <RoundedBox
          args={[width, height, 0.13]}
          radius={0.045}
          smoothness={5}
          onPointerOver={(event) => {
            event.stopPropagation();
            setHovered(true);
            document.body.style.cursor = "pointer";
          }}
          onPointerOut={(event) => {
            event.stopPropagation();
            setHovered(false);
            setPressed(false);
            document.body.style.cursor = "default";
          }}
          onPointerDown={(event) => {
            event.stopPropagation();
            setPressed(true);
          }}
          onPointerUp={(event) => {
            event.stopPropagation();
            if (!pressed) return;
            setPressed(false);
            onClick();
          }}
        >
          <meshStandardMaterial
            ref={materialRef}
            color={color}
            emissive={color}
            emissiveIntensity={0}
            roughness={0.5}
            metalness={0.04}
          />
        </RoundedBox>
        <group position={[0, 0, 0.067]}>
          <TransportIcon
            kind={iconKind}
            size={Math.min(width, height) * 0.44}
            color={icon}
          />
        </group>
      </group>
      <Text
        color="#7f6b4f"
        font={FONT_PIXEL}
        fontSize={0.048}
        position={[0, -0.255, 0.006]}
        anchorX="center"
        anchorY="middle"
      >
        {label}
      </Text>
    </group>
  );
}

