// ── LCD panel ──────────────────────────────────────────────────────────────

function ScreenPanel({
  stateRef,
  albumArtUrl,
  energyRef,
}: {
  stateRef: RefObject<ScreenState>;
  albumArtUrl: string;
  energyRef: RefObject<number>;
}) {
  const { ctx, texture, scratch } = useMemo(() => {
    const canvas = document.createElement("canvas");
    canvas.width = SCREEN_PX_W;
    canvas.height = SCREEN_PX_H;
    const ctx = canvas.getContext("2d");
    const scratchCanvas = document.createElement("canvas");
    scratchCanvas.width = 48;
    scratchCanvas.height = 48;
    const scratch = scratchCanvas.getContext("2d");
    if (!ctx || !scratch) {
      throw new Error("2D canvas is unavailable");
    }

    const texture = new THREE.CanvasTexture(canvas);
    texture.colorSpace = THREE.SRGBColorSpace;
    texture.magFilter = THREE.NearestFilter;
    texture.minFilter = THREE.LinearMipmapLinearFilter;
    texture.generateMipmaps = true;
    texture.anisotropy = 4;

    return { canvas, ctx, texture, scratch };
  }, []);

  const sheenTexture = useMemo(() => makeSheenTexture(), []);
  const artRef = useRef<HTMLImageElement | null>(null);
  const marqueeRef = useRef({ track: "", start: 0 });
  const peaksRef = useRef<number[]>([]);
  const lastDrawRef = useRef(-1);
  const glowRef = useRef<THREE.MeshBasicMaterial>(null);

  useEffect(() => {
    return () => {
      texture.dispose();
    };
  }, [texture]);

  useEffect(() => {
    return () => {
      sheenTexture.dispose();
    };
  }, [sheenTexture]);

  useEffect(() => {
    void document.fonts.load("700 14px 'Bitwave Pixel'");
    void document.fonts.load("400 7px 'Bitwave Pixel'");
  }, []);

  useEffect(() => {
    let cancelled = false;
    artRef.current = null;

    const load = (src: string, canFallBack: boolean) => {
      const image = new Image();
      image.crossOrigin = "anonymous";
      image.onload = () => {
        if (!cancelled) artRef.current = image;
      };
      image.onerror = () => {
        if (!cancelled && canFallBack) load(PLACEHOLDER_ALBUM_ART, false);
      };
      image.src = src;
    };

    if (albumArtUrl) load(albumArtUrl, true);
    else load(PLACEHOLDER_ALBUM_ART, false);

    return () => {
      cancelled = true;
    };
  }, [albumArtUrl]);

  useFrame(({ clock }) => {
    const t = clock.elapsedTime;

    // The LCD refreshes at 12 fps; a faster rate buys nothing on a 320×180
    // canvas and this runs on the same thread as the WebGL frame.
    if (t - lastDrawRef.current < 1 / 12) return;
    lastDrawRef.current = t;

    const state = stateRef.current;
    if (!state) return;
    drawScreen(ctx, t, state, artRef.current, scratch, marqueeRef, peaksRef);
    texture.needsUpdate = true;

    if (glowRef.current) {
      glowRef.current.opacity = 0.05 + energyRef.current * 0.06;
    }
  });

  return (
    <group position={[SCREEN_X, SCREEN_Y, 0]}>
      {/* Terracotta printed frame, then the dark bezel. */}
      <RoundedBox
        args={[SCREEN_W + 0.28, SCREEN_H + 0.28, 0.05]}
        radius={0.07}
        smoothness={5}
        position={[0, 0, 0.325]}
      >
        <meshStandardMaterial color={TERRA} roughness={0.55} metalness={0.05} />
      </RoundedBox>
      <RoundedBox
        args={[SCREEN_W + 0.18, SCREEN_H + 0.18, 0.09]}
        radius={0.06}
        smoothness={5}
        position={[0, 0, 0.35]}
      >
        <meshStandardMaterial color={INK} roughness={0.42} metalness={0.12} />
      </RoundedBox>
      <RoundedBox
        args={[SCREEN_W + 0.06, SCREEN_H + 0.06, 0.02]}
        radius={0.03}
        smoothness={4}
        position={[0, 0, 0.395]}
      >
        <meshStandardMaterial
          color="#07100b"
          roughness={0.35}
          metalness={0.1}
        />
      </RoundedBox>

      {/* The LCD itself. */}
      <mesh position={[0, 0, 0.406]}>
        <planeGeometry args={[SCREEN_W, SCREEN_H]} />
        <meshBasicMaterial map={texture} toneMapped={false} />
      </mesh>

      {/* Glass sheen + a soft bloom plane so the screen lights the bezel. */}
      <mesh position={[0, 0, 0.409]}>
        <planeGeometry args={[SCREEN_W, SCREEN_H]} />
        <meshBasicMaterial
          map={sheenTexture}
          transparent
          opacity={0.55}
          depthWrite={false}
        />
      </mesh>
      <mesh position={[0, 0, 0.412]}>
        <planeGeometry args={[SCREEN_W + 0.1, SCREEN_H + 0.1]} />
        <meshBasicMaterial
          ref={glowRef}
          color={LCD_CORAL}
          transparent
          opacity={0.06}
          depthWrite={false}
        />
      </mesh>
    </group>
  );
}

