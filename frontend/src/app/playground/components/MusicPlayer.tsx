function readMs(value: bigint | string | number | undefined) {
  const ms = Number(value ?? 0);
  return Number.isFinite(ms) && ms > 0 ? ms : 0;
}

function formatTime(ms: number) {
  const totalSeconds = Math.floor(ms / 1000);
  const minutes = Math.floor(totalSeconds / 60);
  const seconds = totalSeconds % 60;
  return `${minutes}:${seconds.toString().padStart(2, "0")}`;
}

function getProgressRatio(progressMs: number, durationMs: number) {
  if (durationMs <= 0) return 0;
  return Math.min(1, Math.max(0, progressMs / durationMs));
}

function clamp01(value: number) {
  return Math.min(1, Math.max(0, value));
}

// A deterministic "audio" signal — layered sines instead of an analyser, since
// there is no audio element to analyse. It drives the speaker cone, the key
// glow and the LCD's bar graph at the same time.
function pseudoLevel(t: number, seed = 0) {
  const value =
    0.48 +
    0.3 * Math.sin(t * 5.3 + seed * 1.9) +
    0.14 * Math.sin(t * 9.7 + seed * 0.6 + 2.1) +
    0.08 * Math.sin(t * 15.1 + seed * 2.7);
  return clamp01(value);
}

