function readMs(value: string | number | undefined) {
  const ms = Number(value ?? 0);
  return Number.isFinite(ms) && ms > 0 ? ms : 0;
}

function formatTime(ms: number) {
  const totalSeconds = Math.floor(ms / 1000);
  const minutes = Math.floor(totalSeconds / 60);
  const seconds = totalSeconds % 60;
  return `${minutes}:${seconds.toString().padStart(2, "0")}`;
}

function getProgressRatio(progressMs: number, durationMs: number) {
  if (durationMs <= 0) return 0;
  return Math.min(1, Math.max(0, progressMs / durationMs));
}

// ── CRT Screen Glow ───────────────────────────────────────────────────────

function CRTGlow({ playing }: { playing: boolean }) {
  const glowRef = useRef<THREE.Mesh>(null);
  useFrame(({ clock }) => {
    if (!glowRef.current) return;
    const flicker = playing
      ? 0.18 + Math.sin(clock.elapsedTime * 60) * 0.01 + Math.sin(clock.elapsedTime * 7) * 0.03
      : 0.08;
    (glowRef.current.material as THREE.MeshBasicMaterial).opacity = flicker;
  });
  return (
    <mesh ref={glowRef} position={[0, 0.38, SCREEN_SURFACE_Z + 0.002]}>
      <planeGeometry args={[3.6, 2.2]} />
      <meshBasicMaterial color={TERM_GREEN} transparent opacity={0.08} depthWrite={false} />
    </mesh>
  );
}

