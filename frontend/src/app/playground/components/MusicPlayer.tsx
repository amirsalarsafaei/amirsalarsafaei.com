function drawFallbackArt(
  ctx: CanvasRenderingContext2D,
  x: number,
  y: number,
  size: number,
) {
  ctx.fillStyle = "#0f241b";
  ctx.fillRect(x, y, size, size);

  const pad = Math.round(size * 0.16);
  const bodyW = size - pad * 2;
  const bodyH = Math.round(size * 0.58);
  const bodyY = y + Math.round(size * 0.24);

  ctx.fillStyle = LCD_BUTTER;
  ctx.fillRect(x + pad, bodyY, bodyW, bodyH);
  ctx.fillStyle = LCD_CORAL;
  ctx.fillRect(x + pad, bodyY, bodyW, Math.round(size * 0.1));
  ctx.fillStyle = LCD_INK;
  ctx.fillRect(
    x + pad + Math.round(size * 0.13),
    bodyY + Math.round(size * 0.15),
    bodyW - Math.round(size * 0.26),
    Math.round(size * 0.2),
  );
  ctx.fillStyle = LCD_MINT;
  ctx.fillRect(
    x + Math.round(size * 0.22),
    bodyY + Math.round(size * 0.46),
    Math.round(size * 0.56),
    Math.round(size * 0.05),
  );

  // Two reels in the window.
  const reelY = bodyY + Math.round(size * 0.25);
  [0.35, 0.65].forEach((fraction) => {
    ctx.fillStyle = LCD_CREAM;
    ctx.beginPath();
    ctx.arc(x + size * fraction, reelY, size * 0.07, 0, Math.PI * 2);
    ctx.fill();
    ctx.fillStyle = LCD_INK;
    ctx.beginPath();
    ctx.arc(x + size * fraction, reelY, size * 0.025, 0, Math.PI * 2);
    ctx.fill();
  });
}

function drawAlbumArt(
  ctx: CanvasRenderingContext2D,
  img: HTMLImageElement | null,
  scratch: CanvasRenderingContext2D,
  x: number,
  y: number,
  size: number,
) {
  // Coral drop shadow + cream printed border, like a sticker on the glass.
  fillRounded(ctx, x + 3, y + 3, size, size, 2, LCD_CORAL);
  fillRounded(ctx, x - 2, y - 2, size + 4, size + 4, 2, LCD_CREAM);

  ctx.save();
  roundedPath(ctx, x, y, size, size, 1);
  ctx.clip();

  if (img) {
    // Downsample first, then blow it back up without smoothing: a chunky,
    // deliberately low-resolution cover that belongs on this LCD.
    const pixels = 48;
    scratch.clearRect(0, 0, pixels, pixels);
    scratch.imageSmoothingEnabled = true;
    scratch.drawImage(img, 0, 0, pixels, pixels);
    ctx.imageSmoothingEnabled = false;
    ctx.drawImage(scratch.canvas, 0, 0, pixels, pixels, x, y, size, size);
    ctx.imageSmoothingEnabled = true;
  } else {
    drawFallbackArt(ctx, x, y, size);
  }

  // A faint green glass tint over the artwork.
  ctx.fillStyle = "rgba(147, 230, 194, 0.08)";
  ctx.fillRect(x, y, size, size);
  ctx.restore();
}

function drawCornerBrackets(ctx: CanvasRenderingContext2D) {
  ctx.strokeStyle = "rgba(147, 230, 194, 0.22)";
  ctx.lineWidth = 1;
  const corners = [
    [5, 5, 1, 1],
    [315, 5, -1, 1],
    [5, 175, 1, -1],
    [315, 175, -1, -1],
  ];
  corners.forEach(([x, y, sx, sy]) => {
    ctx.beginPath();
    ctx.moveTo(x + 8 * sx, y);
    ctx.lineTo(x, y);
    ctx.lineTo(x, y + 8 * sy);
    ctx.stroke();
  });
}

function drawBootScreen(
  ctx: CanvasRenderingContext2D,
  t: number,
  status: PlayerStatus,
) {
  const isError = status === "error";

  drawText(ctx, "BITWAVE", 160, 44, 26, LCD_MINT, true, "center");
  drawText(ctx, "BW-01 · PORTABLE AUDIO", 160, 76, 7, LCD_DIM, false, "center");

  // Segmented loading strip.
  const blocks = 20;
  const lit = Math.floor((t * 10) % (blocks + 7));
  for (let i = 0; i < blocks; i += 1) {
    ctx.fillStyle = i <= lit ? LCD_CORAL : LCD_DIM_DARK;
    ctx.fillRect(70 + i * 9, 96, 7, 6);
  }

  if (isError) {
    drawText(ctx, "NO SIGNAL", 160, 118, 18, LCD_CORAL, true, "center");
    drawText(
      ctx,
      "SPOTIFY LINK FAILED",
      160,
      140,
      7,
      LCD_CREAM,
      false,
      "center",
    );
    const dots = ".".repeat(1 + (Math.floor(t * 2) % 3));
    drawText(ctx, `RETRYING${dots}`, 160, 154, 7, LCD_DIM, false, "center");

    // Sparse static, so the failure state still feels alive.
    for (let i = 0; i < 90; i += 1) {
      const x = Math.floor(Math.random() * 320);
      const y = Math.floor(Math.random() * 180);
      ctx.fillStyle = Math.random() > 0.5 ? LCD_DIM_DARK : LCD_DIM;
      ctx.fillRect(x, y, 1, 1);
    }
  } else {
    const dots = ".".repeat(1 + (Math.floor(t * 2) % 3));
    drawText(
      ctx,
      `LINKING TO SPOTIFY${dots}`,
      160,
      118,
      8,
      LCD_CREAM,
      true,
      "center",
    );
    drawText(
      ctx,
      "AWAITING FIRST TRACK",
      160,
      136,
      7,
      LCD_DIM,
      false,
      "center",
    );
  }

  drawText(ctx, "$ bitwave --boot", 8, 162, 7, LCD_DIM, false, "left");
  drawText(ctx, "SIDE A", 312, 162, 7, LCD_DIM, false, "right");
}

function drawNowPlaying(
  ctx: CanvasRenderingContext2D,
  t: number,
  state: ScreenState,
  art: HTMLImageElement | null,
  scratch: CanvasRenderingContext2D,
  marquee: RefObject<{ track: string; start: number }>,
  peaks: RefObject<number[]>,
) {
  const { track, artist, playing, demo, volume } = state;
  const title = track || "NO TRACK";
  const artistName = artist || "unknown artist";

  // ── Status bar ───────────────────────────────────────────────────────────
  if (playing) {
    drawPlayGlyph(ctx, 9, 6, LCD_MINT);
  } else {
    drawPauseGlyph(ctx, 9, 6, LCD_DIM);
  }
  drawText(ctx, playing ? "NOW PLAYING" : "PAUSED", 20, 6, 8, LCD_CREAM, true);
  drawText(ctx, "BITWAVE", 160, 7, 7, LCD_DIM, false, "center");
  drawText(ctx, "MP3", 282, 7, 7, LCD_DIM, false, "right");
  drawBattery(ctx, 288, 6, 0.86, LCD_DIM);
  ctx.fillStyle = "rgba(147, 230, 194, 0.12)";
  ctx.fillRect(6, 17, 308, 1);

  // ── Source chip ──────────────────────────────────────────────────────────
  const chipLabel = demo ? "OFFLINE DEMO" : "SPOTIFY LIVE";
  const chipColor = demo ? LCD_BUTTER : LCD_MINT;
  setFont(ctx, 7, "normal");
  const chipWidth = Math.ceil(ctx.measureText(chipLabel).width) + 17;
  fillRounded(ctx, 104, 19, chipWidth, 12, 2, "rgba(147, 230, 194, 0.08)");
  roundedPath(ctx, 104, 19, chipWidth, 12, 2);
  ctx.strokeStyle = chipColor;
  ctx.globalAlpha = 0.55;
  ctx.lineWidth = 1;
  ctx.stroke();
  ctx.globalAlpha = 1;
  ctx.fillStyle = chipColor;
  ctx.beginPath();
  ctx.arc(110, 25, 2.5, 0, Math.PI * 2);
  ctx.fill();
  drawText(ctx, chipLabel, 117, 22, 7, chipColor, true);

  // ── Cover + track info ───────────────────────────────────────────────────
  drawAlbumArt(ctx, art, scratch, 8, 20, ART_SIZE);

  if (marquee.current.track !== title) {
    marquee.current = { track: title, start: t };
  }

  const infoX = 104;
  const infoW = 208;
  ctx.save();
  ctx.beginPath();
  ctx.rect(infoX, 34, infoW, 18);
  ctx.clip();
  setFont(ctx, 14, "bold");
  const titleWidth = ctx.measureText(title).width;
  ctx.textBaseline = "top";
  ctx.fillStyle = LCD_CREAM;
  if (titleWidth <= infoW) {
    ctx.fillText(title, infoX, 34);
  } else {
    const gap = 26;
    const span = titleWidth + gap;
    const offset = ((t - marquee.current.start) * 24) % span;
    ctx.fillText(title, infoX - offset, 34);
    ctx.fillText(title, infoX - offset + span, 34);
  }
  ctx.restore();

  setFont(ctx, 9, "normal");
  let artistLabel = artistName;
  if (ctx.measureText(artistLabel).width > infoW) {
    while (
      artistLabel.length > 1 &&
      ctx.measureText(`${artistLabel}...`).width > infoW
    ) {
      artistLabel = artistLabel.slice(0, -1);
    }
    artistLabel = `${artistLabel}...`;
  }
  drawText(ctx, artistLabel, infoX, 55, 9, LCD_MINT, false);

  // ── Spectrum ─────────────────────────────────────────────────────────────
  const barCount = 26;
  const barWidth = 6;
  const barGap = 2;
  const baseline = 108;
  const maxBar = 28;
  const gradient = ctx.createLinearGradient(0, baseline, 0, baseline - maxBar);
  gradient.addColorStop(0, LCD_CORAL);
  gradient.addColorStop(0.55, LCD_BUTTER);
  gradient.addColorStop(1, LCD_MINT);

  if (peaks.current.length !== barCount) {
    peaks.current = new Array(barCount).fill(0);
  }

  for (let i = 0; i < barCount; i += 1) {
    const envelope = 0.55 + 0.45 * Math.sin((i / (barCount - 1)) * Math.PI);
    const target = playing
      ? clamp01(pseudoLevel(t, i * 0.7) * envelope * (0.7 + volume * 0.035))
      : 0;
    const height = Math.max(1, Math.round(target * maxBar));
    const x = infoX + i * (barWidth + barGap);

    ctx.fillStyle = playing ? gradient : LCD_DIM_DARK;
    ctx.fillRect(x, baseline - height, barWidth, height);

    peaks.current[i] = Math.max(height, Math.floor(peaks.current[i] - 0.9));
    if (peaks.current[i] > 1) {
      ctx.fillStyle = LCD_CREAM;
      ctx.fillRect(x, baseline - peaks.current[i] - 2, barWidth, 1);
    }
  }

  // Baseline
  ctx.fillStyle = "rgba(147, 230, 194, 0.16)";
  ctx.fillRect(infoX, baseline + 1, barCount * (barWidth + barGap) - barGap, 1);

  // ── Progress ─────────────────────────────────────────────────────────────
  const progress = state.progressRef.current;
  const elapsedSince = progress.playing ? Date.now() - progress.startedAt : 0;
  const currentMs =
    progress.durationMs > 0
      ? Math.min(progress.durationMs, progress.baseMs + elapsedSince)
      : progress.baseMs;
  const ratio = getProgressRatio(currentMs, progress.durationMs);

  drawText(ctx, formatTime(currentMs), 8, 112, 8, LCD_CREAM, true);
  drawText(
    ctx,
    progress.durationMs > 0 ? formatTime(progress.durationMs) : "--:--",
    312,
    112,
    8,
    LCD_CREAM,
    true,
    "right",
  );

  const segmentCount = 38;
  const segmentWidth = 6;
  const segmentGap = 2;
  const filled = ratio * segmentCount;
  for (let i = 0; i < segmentCount; i += 1) {
    const x = 8 + i * (segmentWidth + segmentGap);
    const isHead = i === Math.floor(filled) && ratio < 1;
    ctx.fillStyle = isHead
      ? LCD_CORAL
      : i < filled
        ? i / segmentCount > 0.72
          ? LCD_CORAL
          : LCD_CREAM
        : LCD_DIM_DARK;
    ctx.fillRect(x, isHead ? 123 : 124, segmentWidth, isHead ? 9 : 7);
  }

  // ── Volume + bitrate ─────────────────────────────────────────────────────
  drawText(ctx, "VOL", 8, 140, 6, LCD_DIM, true);
  for (let i = 0; i < 10; i += 1) {
    ctx.fillStyle = i < volume ? LCD_MINT : LCD_DIM_DARK;
    ctx.fillRect(29 + i * 7, 140, 5, 6);
  }
  drawText(ctx, "320 KBPS · STEREO", 312, 140, 6, LCD_DIM, false, "right");

  // ── Footer line ──────────────────────────────────────────────────────────
  const notice = state.noticeRef.current;
  if (notice.until > Date.now()) {
    drawText(ctx, notice.text, 8, 162, 7, LCD_CORAL, true, "left");
  } else {
    drawText(
      ctx,
      "$ bitwave --now-playing",
      8,
      162,
      7,
      "#476a58",
      false,
      "left",
    );
    if (Math.floor(t * 2) % 2 === 0) {
      setFont(ctx, 7, "normal");
      const cursorX = 8 + ctx.measureText("$ bitwave --now-playing").width + 3;
      ctx.fillStyle = LCD_MINT;
      ctx.fillRect(cursorX, 162, 4, 7);
    }
  }
  drawText(ctx, "SIDE A", 312, 162, 7, LCD_DIM, false, "right");
}

function drawScreenOverlay(ctx: CanvasRenderingContext2D) {
  // Scanlines
  ctx.fillStyle = "rgba(0, 0, 0, 0.10)";
  for (let y = 0; y < SCREEN_PX_H; y += 2) {
    ctx.fillRect(0, y, SCREEN_PX_W, 1);
  }

  // Vignette
  const vignette = ctx.createRadialGradient(160, 90, 46, 160, 90, 190);
  vignette.addColorStop(0, "rgba(0, 0, 0, 0)");
  vignette.addColorStop(1, "rgba(0, 0, 0, 0.38)");
  ctx.fillStyle = vignette;
  ctx.fillRect(0, 0, SCREEN_PX_W, SCREEN_PX_H);

  drawCornerBrackets(ctx);
}

function drawScreen(
  ctx: CanvasRenderingContext2D,
  t: number,
  state: ScreenState,
  art: HTMLImageElement | null,
  scratch: CanvasRenderingContext2D,
  marquee: RefObject<{ track: string; start: number }>,
  peaks: RefObject<number[]>,
) {
  const background = ctx.createLinearGradient(0, 0, 0, SCREEN_PX_H);
  background.addColorStop(0, LCD_BG_TOP);
  background.addColorStop(1, LCD_BG_BOTTOM);
  ctx.fillStyle = background;
  ctx.fillRect(0, 0, SCREEN_PX_W, SCREEN_PX_H);

  // Dot matrix, barely there.
  ctx.fillStyle = "rgba(147, 230, 194, 0.035)";
  for (let y = 4; y < SCREEN_PX_H; y += 8) {
    for (let x = 4; x < SCREEN_PX_W; x += 8) {
      ctx.fillRect(x, y, 1, 1);
    }
  }

  if (state.status === "pending" || state.status === "error") {
    drawBootScreen(ctx, t, state.status);
  } else {
    drawNowPlaying(ctx, t, state, art, scratch, marquee, peaks);
  }

  drawScreenOverlay(ctx);
}

