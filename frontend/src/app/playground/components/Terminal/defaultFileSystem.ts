function addDir(
  fs: FileSystem,
  parent: FsNode,
  parentPath: string,
  name: string,
  mode = 0o755,
  uid = 0,
  gid = 0,
): FsNode {
  const node = new FsNode("directory", { mode, uid, gid });
  parent.children!.set(name, node);
  void fs;
  void joinPath(parentPath, name);
  return node;
}

function addFile(
  parent: FsNode,
  name: string,
  content: string,
  mode = 0o644,
  uid = 0,
  gid = 0,
): FsNode {
  const node = new FsNode("file", { mode, uid, gid, content });
  parent.children!.set(name, node);
  return node;
}

function addLink(parent: FsNode, name: string, target: string): FsNode {
  const node = new FsNode("symlink", { target, uid: 0, gid: 0 });
  parent.children!.set(name, node);
  return node;
}

