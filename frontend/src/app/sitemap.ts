import type { MetadataRoute } from "next";
import { create } from "@bufbuild/protobuf";
import { ListPublishedBlogsRequestSchema } from "@amirsalarsafaei/autogenerated/blogs/blogs_pb";
import { createGrpcClients } from "@/clients/grpc";
import { timestampToDate } from "@/utils/protobuf";
import { getSiteUrl } from "@/utils/seo";

// Regenerated at least every 5 minutes (matching the blog ISR window) so newly
// published posts show up for crawlers without a redeploy. The production
// image is built with NEXT_BUILD_SKIP_BACKEND=1, so the build-time copy only
// contains the static routes; the first revalidation after boot picks up the
// real list from the backend.
export const revalidate = 300;

const STATIC_ROUTES: Array<{
  path: string;
  changeFrequency: MetadataRoute.Sitemap[number]["changeFrequency"];
  priority: number;
}> = [
  { path: "", changeFrequency: "weekly", priority: 1 },
  { path: "/blogs", changeFrequency: "daily", priority: 0.9 },
  { path: "/aboutme", changeFrequency: "monthly", priority: 0.7 },
  { path: "/resume", changeFrequency: "monthly", priority: 0.7 },
  { path: "/playground", changeFrequency: "monthly", priority: 0.5 },
  { path: "/terminal", changeFrequency: "monthly", priority: 0.4 },
];

async function publishedBlogRoutes(
  siteUrl: string,
): Promise<MetadataRoute.Sitemap> {
  // Offline/pure Nix builds have no backend to talk to.
  if (process.env.NEXT_BUILD_SKIP_BACKEND === "1") {
    return [];
  }

  const { blogs_client } = createGrpcClients();
  const routes: MetadataRoute.Sitemap = [];

  let pageToken = "";
  try {
    do {
      const res = await blogs_client.listPublishedBlogs(
        create(ListPublishedBlogsRequestSchema, { pageSize: 100, pageToken }),
      );

      for (const blog of res.blogs) {
        routes.push({
          url: `${siteUrl}/blogs/${blog.id}`,
          lastModified: timestampToDate(blog.publishedAt ?? blog.createdAt),
          changeFrequency: "monthly",
          priority: 0.8,
        });
      }

      pageToken = res.nextPageToken;
    } while (pageToken);
  } catch (error) {
    // A backend hiccup must not break the sitemap; keep the static routes and
    // let the next revalidation retry.
    console.warn(
      "sitemap: could not list published blogs; serving static routes only:",
      error,
    );
  }

  return routes;
}

export default async function sitemap(): Promise<MetadataRoute.Sitemap> {
  const siteUrl = getSiteUrl();

  // No lastModified for static routes: stamping "now" on every 5-minute
  // revalidation is a false freshness signal and teaches crawlers to ignore
  // lastmod. Blog entries carry their real publishedAt instead.
  const staticRoutes: MetadataRoute.Sitemap = STATIC_ROUTES.map((route) => ({
    url: `${siteUrl}${route.path}`,
    changeFrequency: route.changeFrequency,
    priority: route.priority,
  }));

  return [...staticRoutes, ...(await publishedBlogRoutes(siteUrl))];
}
