import {
  createClient,
  type CallOptions,
  type Client,
  type Transport,
} from "@connectrpc/connect";
import { createGrpcWebTransport } from "@connectrpc/connect-web";
import { Blogs, Tags } from "@amirsalarsafaei/autogenerated/blogs/blogs_pb";
import { Profile } from "@amirsalarsafaei/autogenerated/profile/profile_pb";
import { Spotify } from "@amirsalarsafaei/autogenerated/playground/spotify_pb";

// Resolve the gRPC-web endpoint. On the server (SSR, build-time SSG/ISR, and
// generateStaticParams/generateMetadata) prefer GRPC_WEB_INTERNAL_URL so we can
// hit the backend directly over localhost without going through the public
// nginx/TLS path. In the browser, only the NEXT_PUBLIC_* value is available
// (and it's the only one that gets inlined into the client bundle), so server
// and browser deliberately use different URLs.
function getGrpcWebUrl(): string {
  if (typeof window === "undefined") {
    return (
      process.env.GRPC_WEB_INTERNAL_URL ||
      process.env.NEXT_PUBLIC_GRPC_WEB_URL ||
      "http://localhost:8000"
    );
  }

  return process.env.NEXT_PUBLIC_GRPC_WEB_URL || "http://localhost:8000";
}

function createTransport(): Transport {
  const baseUrl = getGrpcWebUrl();

  if (typeof window === "undefined") {
    // The backend is Tonic with GrpcWebLayer + accept_http1(true), so speak
    // gRPC-Web over HTTP/1.1. Required dynamically so the Node-only transport
    // never lands in the client bundle (next.config.js ignores it there).
    /* eslint-disable @typescript-eslint/no-require-imports */
    const connectNode =
      require("@connectrpc/connect-node") as typeof import("@connectrpc/connect-node");
    /* eslint-enable @typescript-eslint/no-require-imports */

    return connectNode.createGrpcWebTransport({
      baseUrl,
      httpVersion: "1.1",
    });
  }

  return createGrpcWebTransport({ baseUrl });
}

/**
 * Per-call options carrying the admin token as gRPC-Web metadata. Connect
 * exposes metadata as plain HTTP headers; an empty object means "no options".
 */
export function withAuth(token?: string | null): CallOptions {
  return token ? { headers: { authorization: token } } : {};
}

export interface GrpcClients {
  spotify_client: Client<typeof Spotify>;
  blogs_client: Client<typeof Blogs>;
  tags_client: Client<typeof Tags>;
  profile_client: Client<typeof Profile>;
}

let clientInstance: GrpcClients | null = null;

export function createGrpcClients(): GrpcClients {
  if (clientInstance) {
    return clientInstance;
  }

  const transport = createTransport();

  clientInstance = {
    spotify_client: createClient(Spotify, transport),
    blogs_client: createClient(Blogs, transport),
    tags_client: createClient(Tags, transport),
    profile_client: createClient(Profile, transport),
  };

  return clientInstance;
}

export function isClient(): boolean {
  return typeof window !== "undefined";
}
