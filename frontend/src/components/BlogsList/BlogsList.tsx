"use client";

import { useEffect, useRef } from "react";
import { type Blog } from "@amirsalarsafaei/autogenerated/blogs/blogs_pb";
import { timestampToDate } from "@/utils/protobuf";
import Link from "next/link";
import Image from "next/image";

import { Chip } from "@/components/Chip/Chip";
import styles from "./BlogsList.module.scss";

interface BlogsProps {
  blogs: Blog[];
  isAdmin: boolean;
  isLoadingError: boolean;
  isFetching: boolean;
  isFetchingNextPage?: boolean;
  hasNextPage?: boolean;
  onLoadMore?: () => void;
  onRetry?: () => void;
}

const dateFormatter = new Intl.DateTimeFormat("en-US", {
  year: "numeric",
  month: "short",
  day: "numeric",
});

function formatDate(value?: Date) {
  return value ? dateFormatter.format(value) : "";
}

export default function BlogsList({
  blogs,
  isFetching,
  isLoadingError,
  isAdmin,
  isFetchingNextPage = false,
  hasNextPage = false,
  onLoadMore,
  onRetry,
}: BlogsProps) {
  const sentinelRef = useRef<HTMLDivElement | null>(null);

  // Infinite scroll: fetch the next page a little before the sentinel is hit.
  useEffect(() => {
    if (!onLoadMore || !hasNextPage || isFetchingNextPage) return;

    const sentinel = sentinelRef.current;
    if (!sentinel || typeof IntersectionObserver === "undefined") return;

    const observer = new IntersectionObserver(
      (entries) => {
        if (entries[0]?.isIntersecting) onLoadMore();
      },
      { rootMargin: "400px 0px" },
    );

    observer.observe(sentinel);
    return () => observer.disconnect();
  }, [onLoadMore, hasNextPage, isFetchingNextPage]);

  if (isLoadingError) {
    return (
      <div className={styles.blogsContainer}>
        <div className={styles.stateCard}>
          <pre
            className={styles.statePrompt}
          >{`$ curl /blogs\nconnection refused`}</pre>
          <p>Could not load posts right now.</p>
          {onRetry && (
            <button
              type="button"
              className={styles.stateAction}
              onClick={onRetry}
            >
              retry
            </button>
          )}
        </div>
      </div>
    );
  }

  if (blogs.length === 0) {
    return (
      <div className={styles.blogsContainer}>
        {isFetching ? (
          <div className={styles.blogsLoading} role="status">
            <span className={styles.spinner} aria-hidden />
            <p>Loading posts...</p>
          </div>
        ) : (
          <div className={styles.stateCard}>
            <pre
              className={styles.statePrompt}
            >{`$ ls ~/blogs\nno posts found`}</pre>
            <p>
              {isAdmin
                ? "Create your first post and it will show up here."
                : "Nothing published yet — check back soon."}
            </p>
            <Link
              className={styles.stateAction}
              href={isAdmin ? "/admin/blogs/new" : "/"}
            >
              {isAdmin ? "new post" : "back home"} <span aria-hidden>→</span>
            </Link>
          </div>
        )}
      </div>
    );
  }

  return (
    <div className={styles.blogsContainer}>
      <div className={styles.blogsGrid}>
        {blogs.map((blog) => (
          <Link
            href={`${isAdmin ? "/admin" : ""}/blogs/${blog.id}`}
            key={blog.id}
            className={styles.blogCardLink}
          >
            <article className={styles.blogCard}>
              {blog.imageUrl ? (
                <div className={styles.blogImage}>
                  <div className={styles.imageOverlay}>
                    <span className={styles.codeLine}>{"</"}</span>
                    <span className={styles.codeTag}>blog</span>
                    <span className={styles.codeLine}>{">"}</span>
                  </div>
                  <Image
                    src={blog.imageUrl}
                    alt={blog.title}
                    width={600}
                    height={340}
                    className={styles.blogCardImage}
                    loading="lazy"
                    quality={80}
                    sizes="(max-width: 768px) 100vw, (max-width: 1200px) 80vw, 840px"
                    // Upload URLs point at the image-server origin (often a
                    // different host/port than the Next server); let the
                    // browser fetch them directly instead of the server-side
                    // optimizer.
                    unoptimized
                  />
                </div>
              ) : (
                <div
                  className={`${styles.blogImage} ${styles.imagePlaceholder}`}
                >
                  <span aria-hidden>{"<blog />"}</span>
                </div>
              )}

              <div className={styles.blogContent}>
                <h3 className={styles.blogTitle}>{blog.title}</h3>

                <div className={styles.blogMeta}>
                  <time
                    className={styles.blogDate}
                    dateTime={timestampToDate(
                      isAdmin ? blog.createdAt : blog.publishedAt,
                    )?.toISOString()}
                  >
                    {formatDate(
                      timestampToDate(
                        isAdmin ? blog.createdAt : blog.publishedAt,
                      ),
                    )}
                  </time>

                  {blog.tags && blog.tags.length > 0 && (
                    <div className={styles.blogTags}>
                      {blog.tags.map((tag) => (
                        <Chip key={tag.id} label={tag.name} />
                      ))}
                    </div>
                  )}
                </div>
              </div>
            </article>
          </Link>
        ))}
      </div>

      <div ref={sentinelRef} className={styles.sentinel} aria-hidden />

      {isFetchingNextPage && (
        <div className={styles.blogsLoading} role="status">
          <span className={styles.spinner} aria-hidden />
          <p>Loading more posts...</p>
        </div>
      )}

      {!hasNextPage && (
        <p className={styles.feedEnd} aria-hidden>
          // end of feed
        </p>
      )}
    </div>
  );
}
